// Devuelve un ícono distinto según el tipo de ingrediente.
// Se usan SVG en lugar de emojis para mantener el estilo delicado del menú.
function obtenerIconoIngrediente(ingrediente) {
  const texto = ingrediente.toLowerCase();

  if (texto.includes("hielo")) {
    return `
      <svg viewBox="0 0 24 24" aria-hidden="true">
        <path d="M12 2.8 20 7v10l-8 4.2L4 17V7l8-4.2Z"/>
        <path d="M4.4 7.2 12 11l7.6-3.8M12 11v9.7M8 5l8 4.1"/>
      </svg>`;
  }

  if (texto.includes("leche")) {
    return `
      <svg viewBox="0 0 24 24" aria-hidden="true">
        <path d="M12 2.7S6.8 9.2 6.8 14a5.2 5.2 0 0 0 10.4 0C17.2 9.2 12 2.7 12 2.7Z"/>
      </svg>`;
  }

  if (texto.includes("espresso") || texto.includes("café") || texto.includes("cafe")) {
    return `
      <svg viewBox="0 0 24 24" aria-hidden="true">
        <path d="M5 9h11v5.2A4.8 4.8 0 0 1 11.2 19H9.8A4.8 4.8 0 0 1 5 14.2V9Z"/>
        <path d="M16 10.5h1.4a2.6 2.6 0 1 1 0 5.2H16M8 5.2c0 1 1 1.2 1 2.2M12 4.2c0 1 1 1.2 1 2.2"/>
      </svg>`;
  }

  if (
    texto.includes("fresa") || texto.includes("mango") || texto.includes("sandía") ||
    texto.includes("sandia") || texto.includes("frambuesa") || texto.includes("mora") ||
    texto.includes("manzana") || texto.includes("ferrero") || texto.includes("kinder") ||
    texto.includes("turín") || texto.includes("turin") || texto.includes("oreo")
  ) {
    return `
      <svg viewBox="0 0 24 24" aria-hidden="true">
        <circle cx="8" cy="13" r="3.1"/>
        <circle cx="15.7" cy="14.2" r="3.5"/>
        <circle cx="12" cy="9.3" r="3"/>
        <path d="M10.8 6.7c.2-2 1.7-3.2 3.9-3.6M13 6.3c1.7-.5 3.2 0 4.2 1"/>
      </svg>`;
  }

  if (texto.includes("agua mineral") || texto.includes("perlas")) {
    return `
      <svg viewBox="0 0 24 24" aria-hidden="true">
        <circle cx="8" cy="7" r="2.2"/>
        <circle cx="15.8" cy="5.5" r="1.5"/>
        <circle cx="13" cy="12.5" r="2.5"/>
        <circle cx="7" cy="17" r="1.6"/>
        <circle cx="17" cy="18" r="2"/>
      </svg>`;
  }

  if (texto.includes("matcha") || texto.includes("taro")) {
    return `
      <svg viewBox="0 0 24 24" aria-hidden="true">
        <path d="M19.5 4.6C13.8 4.8 8.3 7.5 6.1 12.3c-1.3 2.9-.4 5.7 1.8 7.1 2.2-5.6 5.3-9.2 9.6-11.4-3.6 2.8-6.1 6.3-7.5 10.7 2.9.5 5.5-.8 7.1-3.5 1.8-3.1 2.1-7 2.4-10.6Z"/>
      </svg>`;
  }

  // Bases, concentrados, crema, caramelo, avellana, amaretto, etc.
  return `
    <svg viewBox="0 0 24 24" aria-hidden="true">
      <path d="M12 2.7S6.8 9.2 6.8 14a5.2 5.2 0 0 0 10.4 0C17.2 9.2 12 2.7 12 2.7Z"/>
      <path d="M10.2 16.6c.8.7 2.2.9 3.3.3"/>
    </svg>`;
}

function crearTarjeta(bebida, index = 0) {
  const retrasoFlotacion = -((index % 6) * 0.72);
  return `
    <article class="drink-card" tabindex="0" role="button" aria-label="Ver ${bebida.name}" data-id="${bebida.id}" style="--float-delay:${retrasoFlotacion}s">
      <div class="drink-image">
        <img src="${bebida.image}" alt="${bebida.name}" loading="lazy">
      </div>
      <h3 class="drink-name">${bebida.name}</h3>
      <div class="drink-price">${formatoPrecio(bebida.price)}</div>
      <div class="tap-hint">Toca para ver detalles</div>
    </article>`;
}

