// Se distribuyen principalmente hacia los laterales y cambian de tamaño/ritmo.

function crearDestellosPagina() {

  let capa = document.querySelector(".page-sparkles");

  if (!capa) {
    capa = document.createElement("div");
    capa.className = "page-sparkles";
    capa.setAttribute("aria-hidden", "true");
    document.body.prepend(capa);
  }

  // Calcula únicamente hasta donde termina realmente el footer.
  // Evita que la capa de estrellas aumente el scroll de la página.
  const footer = document.querySelector(".footer");

  const altoPagina = footer
    ? footer.offsetTop + footer.offsetHeight
    : document.documentElement.clientHeight;


  capa.innerHTML = "";

  // Aproximadamente un detalle cada 260-300 px,
  // con un máximo para mantenerlo limpio.
  const cantidad = Math.max(
    12,
    Math.min(
      28,
      Math.round(altoPagina / 285)
    )
  );

  const simbolos = ["✦", "✧", "⋆", "✧", "✦"];

  // Generador pseudoaleatorio fijo: el acomodo se ve orgánico pero no "salta" al hacer scroll.
  let semilla = 1847;
  const azar = () => {
    semilla = (semilla * 9301 + 49297) % 233280;
    return semilla / 233280;
  };

  for (let i = 0; i < cantidad; i++) {
    const destello = document.createElement("span");
    destello.className = "page-sparkle";
    destello.textContent = simbolos[Math.floor(azar() * simbolos.length)];

    const margenSuperior = 170;
    const espacioUtil = Math.max(300, altoPagina - 260);
    const baseY = margenSuperior + ((i + 0.45) / cantidad) * espacioUtil;
    const y = Math.max(110, Math.min(altoPagina - 70, baseY + (azar() - 0.5) * 120));

    // Alterna izquierda/derecha; algunos quedan un poco más hacia adentro para verse naturales.
    const ladoIzquierdo = i % 2 === 0;
    const cercaBorde = i % 5 !== 0;
    let x;
    if (ladoIzquierdo) {
      x = cercaBorde ? 2.5 + azar() * 10 : 12 + azar() * 10;
    } else {
      x = cercaBorde ? 87.5 + azar() * 9 : 77 + azar() * 10;
    }

    const tamano = 12 + Math.round(azar() * 12);
    const duracion = 5.8 + azar() * 4.8;
    const retraso = -(azar() * duracion);

    destello.style.left = `${x}%`;
    destello.style.top = `${y}px`;
    destello.style.fontSize = `${tamano}px`;
    destello.style.setProperty("--twinkle-duration", `${duracion.toFixed(2)}s`);
    destello.style.setProperty("--twinkle-delay", `${retraso.toFixed(2)}s`);
    capa.appendChild(destello);
  }
}

// Al deslizar la página, la bebida más cercana al centro de la pantalla crece apenas un poco, de forma suave.
// La escala se combina con la animación de flotación sin afectar el clic de la tarjeta.
let frameEscala = null;
function actualizarEscalaBebidas() {
  frameEscala = null;
  const tarjetas = document.querySelectorAll(".drink-card");
  const altoVentana = window.innerHeight || document.documentElement.clientHeight;
  const centroVentana = altoVentana / 2;

  tarjetas.forEach(tarjeta => {
    const rect = tarjeta.getBoundingClientRect();
    if (rect.bottom < 0 || rect.top > altoVentana) {
      tarjeta.style.setProperty("--image-scale", "1");
      return;
    }

    const centroTarjeta = rect.top + rect.height / 2;
    const distancia = Math.abs(centroTarjeta - centroVentana);
    const proximidad = 1 - Math.min(distancia / (altoVentana * 0.72), 1);
    const escala = 1 + proximidad * 0.018;
    tarjeta.style.setProperty("--image-scale", escala.toFixed(3));
  });
}

function solicitarEscalaBebidas() {
  if (frameEscala !== null) return;
  frameEscala = requestAnimationFrame(actualizarEscalaBebidas);
}

let temporizadorResize = null;
function actualizarDecoracionResponsive() {
  solicitarEscalaBebidas();
  clearTimeout(temporizadorResize);
  temporizadorResize = setTimeout(crearDestellosPagina, 120);
}

function renderCategoria(categoria) {
  const meta = textosCategoria[categoria];
  const secciones = ordenSecciones[categoria];
  menuContent.innerHTML = secciones.map((seccion, index) => {
    const items = bebidas.filter(b => b.group === categoria && b.section === seccion);
    const titulo = secciones.length === 1 ? meta.titulo : seccion;
    const subtitulo = index === 0 ? meta.subtitulo : "";
    return `
      <section class="menu-section">
        <header class="section-heading">
          <h2><span class="mini-spark">✧</span> ${titulo} <span class="mini-spark">✧</span></h2>
          ${subtitulo ? `<p>${subtitulo}</p>` : ""}
        </header>
        <div class="drink-grid">${items.map((bebida, itemIndex) => crearTarjeta(bebida, itemIndex)).join("")}</div>
      </section>`;
  }).join("");

  requestAnimationFrame(() => {
    actualizarEscalaBebidas();
    crearDestellosPagina();
  });
}

function abrirModal(id, trigger) {
  const bebida = bebidas.find(b => b.id === id);
  if (!bebida) return;
  lastFocusedElement = trigger || document.activeElement;
  modalImage.src = bebida.image;
  modalImage.alt = bebida.name;
  modalTitle.textContent = bebida.name;
  modalPrice.textContent = formatoPrecio(bebida.price);
  modalDescription.textContent = bebida.description;
  modalIngredients.innerHTML = bebida.ingredients.map(i => `
    <li>
      <span class="ingredient-icon">${obtenerIconoIngrediente(i)}</span>
      <span class="ingredient-text">${i}</span>
    </li>`).join("");
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
  modal.querySelector(".modal-close").focus();
}

function cerrarModal() {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
  if (lastFocusedElement) lastFocusedElement.focus();
}

categoryButtons.forEach(btn => {

  btn.addEventListener("click", () => {

    categoryButtons.forEach(b => b.classList.remove("active"));

    btn.classList.add("active");

    renderCategoria(btn.dataset.category);

    requestAnimationFrame(() => {
      crearDestellosPagina();
    });

    window.scrollTo({
      top: document.querySelector(".category-nav").offsetTop - 8,
      behavior: "smooth"
    });

  });

});

menuContent.addEventListener("click", e => {
  const card = e.target.closest(".drink-card");
  if (card) abrirModal(card.dataset.id, card);
});

menuContent.addEventListener("keydown", e => {
  if ((e.key === "Enter" || e.key === " ") && e.target.classList.contains("drink-card")) {
    e.preventDefault();
    abrirModal(e.target.dataset.id, e.target);
  }
});

